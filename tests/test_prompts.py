from types import SimpleNamespace

from multiagent.agents.base import developer_spec, pm_spec, reviewer_spec
from multiagent.prompts import compose, load, resolve


def test_all_builtin_templates_load() -> None:
    for name in ("developer", "reviewer", "pm_decompose", "pm_fix", "conventions"):
        text = load(name)
        assert text.strip(), f"template {name} is empty"


def test_compose_stacks_sections() -> None:
    combined = compose("developer", "conventions")
    assert combined.index("Layering and SOLID") < 1000
    assert combined.index("developer") < combined.index("Cross-cutting conventions")


def test_conventions_stacked_into_agent_specs(tmp_path) -> None:
    settings = SimpleNamespace(
        dev_model="m", reviewer_model="m", pm_model="m", prompts_dir=None
    )
    assert "Cross-cutting conventions" in developer_spec(settings).system_prompt
    reviewer_prompt = reviewer_spec(settings).system_prompt
    assert "Cross-cutting conventions" in reviewer_prompt
    # The reviewer must know to enforce them, not just follow them.
    assert "finding-worthy" in reviewer_prompt
    assert pm_spec(settings).system_prompt


def test_project_override_wins_and_partial_overrides_fall_back(tmp_path) -> None:
    overrides = tmp_path / ".multiagent"
    overrides.mkdir()
    (overrides / "conventions.md").write_text("# Project-specific conventions\n")
    (overrides / "developer.md").write_text("You are a Rust systems engineer.\n")

    assert resolve("conventions", overrides).startswith("# Project-specific")
    assert resolve("developer", overrides).startswith("You are a Rust")
    # Anything not generated by the discovery phase uses the built-in default.
    assert resolve("reviewer", overrides) == load("reviewer")
    assert resolve("pm_fix", overrides) == load("pm_fix")


def test_no_overrides_dir_means_builtin(tmp_path) -> None:
    assert resolve("developer", tmp_path / "does-not-exist") == load("developer")
    assert resolve("developer", None) == load("developer")


def test_compose_uses_project_overrides(tmp_path) -> None:
    overrides = tmp_path / ".multiagent"
    overrides.mkdir()
    (overrides / "developer.md").write_text("PROJECT DEV PROMPT")
    (overrides / "conventions.md").write_text("PROJECT CONVENTIONS")
    combined = compose("developer", "conventions", overrides_dir=overrides)
    assert combined == "PROJECT DEV PROMPT\n\nPROJECT CONVENTIONS"
    assert "senior software developer" not in combined
